"""Build Flash-resident antialiased ASCII glyphs and an identical host fixture.

Requires Pillow. Supply --font /path/to/DejaVuSans-Bold.ttf; when omitted, use
Matplotlib's installed copy. The source font is DejaVu Sans Bold, covered by
LICENSE.dashboard-font. The TTF itself is not needed by the firmware/build.
"""
import argparse
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]


def generate(source):
    tables = {}
    sections = ['// Generated by tools/generate_dashboard_fonts.py. See LICENSE.dashboard-font.',
                '#pragma once', '#include <Arduino.h>', '#include "../smooth_text.h"', '']
    for name, size in ((9, 16), (12, 22), (18, 34), (24, 46)):
        face = ImageFont.truetype(str(source), size)
        cap_height = -face.getbbox('H', anchor='ls')[1]
        pixels, glyphs = bytearray(), []
        for code in range(32, 127):
            char = chr(code)
            left, top, right, bottom = face.getbbox(char, anchor='ls')
            mask = Image.new('L', (max(1, right-left), max(1, bottom-top)))
            ImageDraw.Draw(mask).text((-left, -top), char, font=face, fill=255, anchor='ls')
            # Crop whitespace so rendering visits only visible glyph bounds.
            bbox = mask.getbbox()
            if bbox:
                mask = mask.crop(bbox)
                dx, dy = left+bbox[0], cap_height+top+bbox[1]
                width, height = mask.size
            else:
                width = height = dx = dy = 0
            offset = len(pixels)
            alpha = [(value * 15 + 127) // 255 for value in mask.tobytes()] if bbox else []
            for index in range(0, len(alpha), 2):
                pixels.append((alpha[index] << 4) | (alpha[index+1] if index+1 < len(alpha) else 0))
            glyphs.append([offset, width, height, round(face.getlength(char)), dx, dy])
        sections.append(f'static constexpr uint8_t kCapHeight{name} = {cap_height};')
        sections.append(f'static const uint8_t kPixels{name}[] PROGMEM = {{')
        sections.extend('  '+','.join(f'0x{v:02x}' for v in pixels[i:i+24])+',' for i in range(0, len(pixels), 24))
        sections.append('};')
        sections.append(f'static const DashboardGlyph kGlyphs{name}[] PROGMEM = {{')
        sections.extend('  {'+','.join(map(str, row))+'},' for row in glyphs)
        sections.append('};\n')
        tables[name] = {'cap_height': cap_height, 'glyphs': glyphs, 'pixels': pixels.hex()}
    output = ROOT/'src/magpie/fonts/dashboard_fonts.h'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(sections)+'\n', encoding='utf-8')
    (ROOT/'tools/dashboard_fonts.json').write_text(json.dumps(tables, separators=(',', ':')), encoding='utf-8')
    print(f'{output}: {sum(len(bytes.fromhex(t["pixels"])) for t in tables.values()):,} bitmap bytes in Flash')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--font', type=Path)
    args = parser.parse_args()
    source = args.font
    if source is None:
        import matplotlib
        source = Path(matplotlib.get_data_path())/'fonts/ttf/DejaVuSans-Bold.ttf'
    generate(source)
